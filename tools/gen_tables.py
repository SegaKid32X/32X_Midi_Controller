#!/usr/bin/env python3
"""Pitch and velocity tables for the 68000's MIDI engine (src/md/md_midi.c).

  ym_fnum[r][i]   YM2612 F-number at block 4 for the pitch i/16 semitones
                  above middle C (MIDI 60), i = 0..191 (one octave)
  psg_tone[r][i]  PSG tone period for the same pitch one octave up (MIDI 72)
  vel_att[v]      TL steps (0.75 dB) to add to the carriers at velocity v

r = 0 NTSC, 1 PAL (the clocks differ). usage: gen_tables.py out.h
"""
import math
import sys

YM = (7670453, 7600489)          # NTSC, PAL: the YM2612's clock
PSG = (3579545, 3546893)


def main() -> int:
    out = []
    out.append("/* generated by tools/gen_tables.py */")
    out.append("static const uint16_t ym_fnum[2][192] = {")
    for clk in YM:
        vals = []
        for i in range(192):
            f = 440.0 * 2 ** ((60 + i / 16 - 69) / 12)
            vals.append(round(f * 2 ** (21 - 4) * 144 / clk))
        out.append("    { " + ", ".join(map(str, vals)) + " },")
    out.append("};")
    out.append("static const uint16_t psg_tone[2][192] = {")
    for clk in PSG:
        vals = []
        for i in range(192):
            f = 440.0 * 2 ** ((72 + i / 16 - 69) / 12)
            vals.append(round(clk / (32 * f)))
        out.append("    { " + ", ".join(map(str, vals)) + " },")
    out.append("};")
    # a velocity curve close to a piano's: 40 log10(v / 127) dB, 0.75 dB a step
    att = []
    for v in range(128):
        db = 0 if v == 0 else -40 * math.log10(v / 127)
        att.append(min(127, round(db / 0.75)) if v else 127)
    out.append("static const uint8_t vel_att[128] = { " + ", ".join(map(str, att)) + " };")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
