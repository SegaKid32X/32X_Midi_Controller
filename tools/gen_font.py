#!/usr/bin/env python3
"""The 32X screen font: a C header with ASCII 32..95, 7 rows of 5 bits each.

From tools/font5x7.py (SegaTube / ZERO SECTOR), plus the characters that turn
up in file names. Lowercase letters are drawn with the uppercase glyphs.

usage: gen_font.py out.h
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from font5x7 import FONT  # noqa: E402

EXTRA = {
    '_': [".....", ".....", ".....", ".....", ".....", ".....", "#####"],
    '#': [".#.#.", ".#.#.", "#####", ".#.#.", "#####", ".#.#.", ".#.#."],
    '&': [".##..", "#..#.", ".##..", ".#...", "#.#.#", "#..#.", ".##.#"],
    ';': [".....", "..#..", ".....", ".....", "..#..", "..#..", ".#..."],
    '[': [".###.", ".#...", ".#...", ".#...", ".#...", ".#...", ".###."],
    ']': [".###.", "...#.", "...#.", "...#.", "...#.", "...#.", ".###."],
    '"': [".#.#.", ".#.#.", ".....", ".....", ".....", ".....", "....."],
    '@': [".###.", "#...#", "#.###", "#.#.#", "#.###", "#....", ".###."],
    '\\': ["#....", "#....", ".#...", "..#..", "...#.", "....#", "....#"],
}


def main() -> int:
    out = sys.argv[1]
    glyphs = dict(FONT)
    for k, v in EXTRA.items():
        glyphs.setdefault(k, v)
    lines = ["/* generated by tools/gen_font.py: ASCII 32..95, 7 rows, bit 4 = left */",
             "static const unsigned char font5x7[64][7] = {"]
    for code in range(32, 96):
        rows = glyphs.get(chr(code), ["....."] * 7)
        vals = [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]
        lines.append("    { " + ", ".join(f"0x{v:02X}" for v in vals) + " },  /* "
                     + (chr(code) if chr(code) not in "\\/*" else "?") + " */")
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
