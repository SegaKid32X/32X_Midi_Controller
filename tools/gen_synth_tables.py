#!/usr/bin/env python3
"""Tables for the 32X's software FM voices (src/32x/fm.c), at 22050 Hz.

  fm_sine[1024]     one sine period, +-8191 (an operator's output range, as
                    the YM2612's 14-bit operators)
  fm_gain[1024+]    attenuation (YM2612 envelope units, 0.09375 dB) -> gain, x4096
  fm_note_inc[128]  phase increment (32-bit phase, 1024-entry table on the top
                    10 bits) of each MIDI note, A4 = 440 Hz
  fm_eg_inc[64]     envelope increment per output sample, 16.16 fixed point,
                    for each effective rate 0-63 (after the YM2612's rate
                    timing: an increment of 1 per envelope clock at rate 44,
                    twice as fast every 4 rates, quarter steps between)
  fm_vel_att[128]   velocity -> 0.75 dB steps (a piano-like curve, as on the
                    68000's engine)

usage: gen_synth_tables.py out.h
"""
import math
import sys

RATE = 22050
EG_CLOCK = 7670453 / 144 / 3     # the YM2612's envelope clock (NTSC)


def main() -> int:
    o = ["/* generated by tools/gen_synth_tables.py */"]
    o.append("static const int16_t fm_sine[1024] = {")
    o.append(", ".join(str(round(8191 * math.sin(2 * math.pi * i / 1024))) for i in range(1024)))
    o.append("};")
    gains = [round(4096 * 10 ** (-(a * 0.09375) / 20)) for a in range(1024 + 128 * 8)]
    o.append(f"#define FM_GAIN_MAX {len(gains) - 1}")
    o.append("static const uint16_t fm_gain[] = {")
    o.append(", ".join(map(str, gains)))
    o.append("};")
    inc = [round(440 * 2 ** ((n - 69) / 12) / RATE * 2 ** 32) for n in range(128)]
    o.append("static const uint32_t fm_note_inc[128] = {")
    o.append(", ".join(f"{v}u" for v in inc))
    o.append("};")
    eg = []
    for r in range(64):
        if r < 4:
            eg.append(0)
            continue
        per_clock = (1 + (r & 3) / 4) * 2 ** (r // 4 - 11)
        eg.append(min(0x7FFFFFFF, round(per_clock * EG_CLOCK / RATE * 65536)))
    o.append("static const uint32_t fm_eg_inc[64] = {")
    o.append(", ".join(f"{v}u" for v in eg))
    o.append("};")
    att = [127] + [min(127, round(-40 * math.log10(v / 127) / 0.75)) for v in range(1, 128)]
    o.append("static const uint8_t fm_vel_att[128] = { " + ", ".join(map(str, att)) + " };")
    open(sys.argv[1], "w").write("\n".join(o) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
